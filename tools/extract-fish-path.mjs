/**
 * Regenerate the plugin's brand assets (`fish-path.js`, `icon.svg`) from the
 * official brand source.
 *
 * The splash markup is built in the HOST half, which runs under DSH's profile
 * resolver. A `link:`-mounted, zero-build local plugin resolves no
 * `@deepseek-ai/*` bare specifier (its realpath lands outside the profile
 * scope, so the resolver falls back to native resolution and misses), and
 * `@deepseek-ai/dsh-client-ui-primitives` is a browser package full of React
 * anyway. So the fish geometry is copied out of the source once and committed
 * as plain data.
 *
 * Usage:
 *   node tools/extract-fish-path.mjs [path/to/FishLogo.tsx]
 *
 * With no argument the source is read from the DSH checkout this plugin was
 * developed against — `DSH_CHECKOUT`, or one found inside/beside this plugin
 * (see `find-checkout.mjs`). No path from the author's machine is baked in.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { findCheckout } from './find-checkout.mjs'

const here = dirname(fileURLToPath(import.meta.url))

/** Brand source, relative to a checkout root. */
const SOURCE_IN_CHECKOUT = join('packages', 'client', 'ui-primitives', 'src', 'FishLogo.tsx')

function defaultSource() {
  const checkout = findCheckout(here)
  if (checkout === undefined) return undefined
  return join(checkout, SOURCE_IN_CHECKOUT)
}

const requested = process.argv[2]
const source = resolve(requested ?? defaultSource() ?? '')
if (requested === undefined && defaultSource() === undefined) {
  process.stderr.write(
    'extract-fish-path: no source given and no DSH checkout found.\n'
    + `  Pass the FishLogo.tsx path directly, or set DSH_CHECKOUT.\n`
    + `  (Looked for <checkout>/${SOURCE_IN_CHECKOUT})\n`,
  )
  process.exit(2)
}

const text = readFileSync(source, 'utf8')

const viewBox = /\bFISH_LOGO_VIEWBOX\s*=\s*\{\s*width:\s*([0-9.]+)\s*,\s*height:\s*([0-9.]+)\s*\}/.exec(text)
if (viewBox === null) throw new Error(`extract-fish-path: FISH_LOGO_VIEWBOX not found in ${source}`)

const path = /\bFISH_LOGO_PATH\s*=\s*'([^']+)'/.exec(text)
if (path === null) throw new Error(`extract-fish-path: FISH_LOGO_PATH not found in ${source}`)

const [, width, height] = viewBox
const data = path[1]

// The row contract forbids these sequences: an inline <script> or <style>
// element would be closed early by the HTML parser.
for (const forbidden of ['</script', '</style']) {
  if (data.includes(forbidden)) throw new Error(`extract-fish-path: path data contains ${forbidden}`)
}

const out = `/**
 * Official DeepSeek Harness fish mark.
 *
 * GENERATED by tools/extract-fish-path.mjs from
 * @deepseek-ai/dsh-client-ui-primitives/src/FishLogo.tsx — do not edit by hand.
 * Re-run the tool after upgrading DSH to pick up brand changes.
 */

/** Native viewBox of {@link FISH_LOGO_PATH} (width and height in user units). */
export const FISH_LOGO_VIEWBOX = { width: ${width}, height: ${height} }

/** The fish silhouette path data. */
export const FISH_LOGO_PATH = ${JSON.stringify(data)}
`

writeFileSync(join(here, '..', 'fish-path.js'), out)

// The plugin icon: the same geometry, fitted into the harness's 32x32 icon
// frame with the mark's own aspect ratio preserved and a 4px margin.
const ICON_FRAME = 32
const ICON_WIDTH = ICON_FRAME - 8
const scale = ICON_WIDTH / Number(width)
const iconHeight = Number(height) * scale
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${ICON_FRAME} ${ICON_FRAME}" width="${ICON_FRAME}" height="${ICON_FRAME}" fill="none">
  <g transform="translate(${(ICON_FRAME - ICON_WIDTH) / 2} ${(ICON_FRAME - iconHeight) / 2}) scale(${scale.toFixed(4)})">
    <path d="${data}" fill="currentColor"/>
  </g>
</svg>
`
writeFileSync(join(here, '..', 'icon.svg'), icon)

process.stdout.write(`extract-fish-path: wrote fish-path.js (viewBox ${width}x${height}, ${data.length} chars) and icon.svg (scale ${scale.toFixed(4)}) from ${source}\n`)
